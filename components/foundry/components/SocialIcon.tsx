import type { ReactNode } from "react";

/** Normalise un nom de réseau saisi par le client ("X", "insta"…) vers une clé. */
function norm(platform: string): string {
  const p = platform.trim().toLowerCase();
  if (/x$|twitter|^x/.test(p)) return "x";
  if (/linkedin|linked/.test(p)) return "linkedin";
  if (/insta/.test(p)) return "instagram";
  if (/face/.test(p)) return "facebook";
  if (/git/.test(p)) return "github";
  if (/mail|email|courriel|contact@|@/.test(p)) return "mail";
  if (/youtube|yt$/.test(p)) return "youtube";
  if (/tiktok|tik/.test(p)) return "tiktok";
  return "link";
}

